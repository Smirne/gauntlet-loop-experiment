/**
 * Baseline, in world units, over which the banking measures how far the road
 * has turned. Sized against the noise it has to see past, not against a corner:
 * control points are 22 u apart and quantised to integers, so anything shorter
 * than about 30 u reports resampling ripple. 35 u is one and a half control
 * spacings — long enough to be immune, short enough that a real R26 chicane
 * still banks. `?bankBaseline=N` overrides it, and 0 restores the old 1.5 u
 * behaviour, so both can be driven from ONE build (D25).
 */
const BANK_BASELINE = (() => {
  const DEFAULT = 35;
  try {
    const v = new URLSearchParams(location.search).get('bankBaseline');
    if (v === null || v === '') return DEFAULT;
    const n = Number(v);
    // Number('') and Number(null) are both 0, which here would mean "no
    // baseline at all"; both are handled above rather than through a >= 0 test.
    return Number.isFinite(n) && n >= 0 ? n : DEFAULT;
  } catch (_) { return DEFAULT; }
})();

/**
 * `?hazardGeom=butterJump:height=14,length=24;foldA:height=3` reshapes named
 * hazards at build time. It exists so a ramp can be re-proportioned and LOOKED
 * AT — mesh, shadow, silhouette and all — without editing the track file and
 * without the two builds differing by anything else.
 *
 * A flag is not a feature. Nothing in the game sets this; it is for tools
 * comparing geometries side by side, and an unparseable value is ignored rather
 * than guessed at, so a typo cannot silently ship a different circuit.
 *
 * @type {Map<string, {height?:number, length?:number, width?:number}>|null}
 */
const HAZARD_GEOM = (() => {
  let raw = '';
  try { raw = new URLSearchParams(location.search).get('hazardGeom') || ''; } catch (_) { return null; }
  if (!raw) return null;
  const map = new Map();
  for (const entry of raw.split(';')) {
    const c = entry.indexOf(':');
    if (c < 1) continue;
    const id = entry.slice(0, c).trim();
    const over = {};
    for (const pair of entry.slice(c + 1).split(',')) {
      const eq = pair.indexOf('=');
      if (eq < 1) continue;
      const key = pair.slice(0, eq).trim();
      const n = Number(pair.slice(eq + 1));
      if (!Number.isFinite(n) || n <= 0) continue;
      if (key === 'height' || key === 'length' || key === 'width') over[key] = n;
    }
    if (id && Object.keys(over).length) map.set(id, over);
  }
  return map.size ? map : null;
})();


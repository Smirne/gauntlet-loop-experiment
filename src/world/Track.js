/** Fold any real into [0,1). Guards the -1e-17 case that floors to -1. */
export function wrap01(t) {
  if (!Number.isFinite(t)) return 0;
  const x = t - Math.floor(t);
  return x >= 1 ? 0 : x < 0 ? 0 : x;
}

/** Shortest signed difference a-b on the unit circle, in [-0.5, 0.5]. */
export function cyclicDelta(a, b) {
  let d = a - b;
  d -= Math.floor(d);
  return d > 0.5 ? d - 1 : d;
}

/**
 * Closed centripetal Catmull-Rom through the given points.
 * Centripetal is not a preference: uniform/chordal Catmull-Rom overshoots into
 * cusps when control-point spacing is uneven, and a cusp in a track centreline
 * is a corner no car can take.
 * @param {Array<Array<number>|THREE.Vector3>} points
 */
export function makeClosedCurve(points) {
  const pts = [];
  for (let i = 0; i < points.length; i++) {
    const p = points[i];
    const v = Array.isArray(p)
      ? new THREE.Vector3(p[0] || 0, p[1] || 0, p[2] || 0)
      : new THREE.Vector3(p.x || 0, p.y || 0, p.z || 0);
    // Catmull-Rom degenerates on coincident knots; drop near-duplicates.
    if (pts.length && v.distanceToSquared(pts[pts.length - 1]) < 1e-4) continue;
    pts.push(v);
  }
  if (pts.length > 2 && pts[0].distanceToSquared(pts[pts.length - 1]) < 1e-4) pts.pop();
  while (pts.length < 4) pts.push(new THREE.Vector3(pts.length * 40, 0, 0));
  const curve = new THREE.CatmullRomCurve3(pts, true, 'centripetal', 0.5);
  curve.arcLengthDivisions = Math.max(600, pts.length * 48);
  return curve;
}

/**
 * Dense chordal arc-length table for a curve.
 * @returns {{u: Float32Array, s: Float32Array, length: number}}
 */
export function buildArcTable(curve, divisions = 4096) {
  const n = Math.max(64, divisions | 0);
  const u = new Float32Array(n + 1);
  const s = new Float32Array(n + 1);
  const a = new THREE.Vector3();
  const b = new THREE.Vector3();
  curve.getPoint(0, a);
  let acc = 0;
  u[0] = 0;
  s[0] = 0;
  for (let i = 1; i <= n; i++) {
    const ui = i / n;
    curve.getPoint(ui, b);
    acc += a.distanceTo(b);
    a.copy(b);
    u[i] = ui;
    s[i] = acc;
  }
  return { u, s, length: acc };
}

/** Invert an arc table: distance along the curve -> curve parameter u. */
export function uAtDistance(table, dist) {
  const s = table.s;
  const n = s.length - 1;
  const total = table.length;
  if (total <= 0) return 0;
  let d = dist % total;
  if (d < 0) d += total;
  let lo = 0;
  let hi = n;
  while (lo + 1 < hi) {
    const mid = (lo + hi) >> 1;
    if (s[mid] <= d) lo = mid; else hi = mid;
  }
  const span = s[hi] - s[lo];
  const f = span > 1e-9 ? (d - s[lo]) / span : 0;
  return table.u[lo] + (table.u[hi] - table.u[lo]) * f;
}

/** In-place cyclic binomial smoothing (1-2-1), `passes` times. */
export function smoothClosed(arr, passes = 1, scratch = null) {
  const n = arr.length;
  if (n < 3 || passes <= 0) return arr;
  const tmp = scratch && scratch.length >= n ? scratch : new Float32Array(n);
  for (let p = 0; p < passes; p++) {
    for (let i = 0; i < n; i++) {
      const a = arr[(i - 1 + n) % n];
      const b = arr[i];
      const c = arr[(i + 1) % n];
      tmp[i] = (a + 2 * b + c) * 0.25;
    }
    for (let i = 0; i < n; i++) arr[i] = tmp[i];
  }
  return arr;
}

/**
 * Evaluate a cyclic piecewise-linear profile [{t, <key>}] at t.
 * Empty profiles fall back to `fallback`; a single entry is constant.
 */
export function evalProfile(profile, t, key, fallback) {
  if (!Array.isArray(profile) || profile.length === 0) return fallback;
  if (profile.length === 1) {
    const v = profile[0][key];
    return typeof v === 'number' ? v : fallback;
  }
  const x = wrap01(t);
  let lo = profile.length - 1;
  let hi = 0;
  for (let i = 0; i < profile.length; i++) {
    if (profile[i].t <= x) lo = i; else { hi = i; break; }
    if (i === profile.length - 1) hi = 0;
  }
  const a = profile[lo];
  const b = profile[hi];
  let span = b.t - a.t;
  if (span <= 0) span += 1;
  let local = x - a.t;
  if (local < 0) local += 1;
  const f = span > 1e-6 ? clamp(local / span, 0, 1) : 0;
  const av = typeof a[key] === 'number' ? a[key] : fallback;
  const bv = typeof b[key] === 'number' ? b[key] : fallback;
  return lerp(av, bv, f);
}


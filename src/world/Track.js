/**
 * A self-contained fallback circuit. Track must construct even if the
 * definition module is missing or malformed — a black screen because a track
 * file has a typo is not an acceptable failure mode.
 */
export function defaultDefinition() {
  const path = [];
  const n = 20;
  for (let i = 0; i < n; i++) {
    const a = (i / n) * TAU;
    // An oval with two asymmetric kinks so the racing line has something to solve.
    const r = 132 + 34 * Math.sin(a * 2 + 0.7) + 12 * Math.sin(a * 3);
    path.push([Math.cos(a) * r * 1.22, 0, Math.sin(a) * r * 0.82]);
  }
  return {
    id: 'fallback',
    name: 'SHAKEDOWN LOOP',
    theme: 'kitchen',
    lighting: 'morning',
    seed: 1337,
    laps: 3,
    difficulty: 1,
    path,
    widthProfile: [{ t: 0, width: 28 }, { t: 0.5, width: 24 }],
    surfaceSpans: [{ from: 0, to: 1, surface: 'varnishedWood' }],
    hazards: [],
    props: [],
    ambient: {},
  };
}


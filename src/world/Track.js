/**
 * Uniform-grid nearest-vertex index over a closed XZ polyline, stored CSR:
 * one prefix-sum array of cell starts plus one flat array of vertex ids. No
 * per-cell arrays, no allocation on query, cache-friendly iteration.
 *
 * Only every `stride`-th vertex is indexed. Localising a query to within
 * stride/2 vertices is all that is needed; the caller refines from there. That
 * keeps the table small enough to stay in L2 for a whole lap.
 */
export class PolylineIndex {
  constructor(px, pz, count, { stride = 4, cell = 16, pad = 80 } = {}) {
    this.px = px;
    this.pz = pz;
    this.count = count;
    this.stride = Math.max(1, stride | 0);
    this.cell = cell;

    let minX = Infinity;
    let minZ = Infinity;
    let maxX = -Infinity;
    let maxZ = -Infinity;
    for (let i = 0; i < count; i++) {
      if (px[i] < minX) minX = px[i];
      if (px[i] > maxX) maxX = px[i];
      if (pz[i] < minZ) minZ = pz[i];
      if (pz[i] > maxZ) maxZ = pz[i];
    }
    if (!Number.isFinite(minX)) { minX = maxX = minZ = maxZ = 0; }

    this.minX = minX - pad;
    this.minZ = minZ - pad;
    this.cols = Math.max(1, Math.ceil((maxX - minX + pad * 2) / cell));
    this.rows = Math.max(1, Math.ceil((maxZ - minZ + pad * 2) / cell));

    const n = Math.ceil(count / this.stride);
    const cells = this.cols * this.rows;
    const start = new Int32Array(cells + 1);
    const cellOf = new Int32Array(n);
    for (let k = 0; k < n; k++) {
      const i = k * this.stride;
      const cx = clamp(Math.floor((px[i] - this.minX) / cell), 0, this.cols - 1);
      const cz = clamp(Math.floor((pz[i] - this.minZ) / cell), 0, this.rows - 1);
      const c = cz * this.cols + cx;
      cellOf[k] = c;
      start[c + 1]++;
    }
    for (let c = 0; c < cells; c++) start[c + 1] += start[c];
    const items = new Int32Array(n);
    const cursor = start.slice(0, cells);
    for (let k = 0; k < n; k++) items[cursor[cellOf[k]]++] = k * this.stride;

    this.start = start;
    this.items = items;
  }

  /** Index of the nearest indexed vertex to (x, z). Never allocates. */
  nearest(x, z) {
    const { cols, rows, cell, start, items, px, pz } = this;
    const cx = clamp(Math.floor((x - this.minX) / cell), 0, cols - 1);
    const cz = clamp(Math.floor((z - this.minZ) / cell), 0, rows - 1);

    let best = -1;
    let bestD = Infinity;
    const maxRing = Math.min(HASH_MAX_RINGS, Math.max(cols, rows));

    for (let ring = 0; ring <= maxRing; ring++) {
      const x0 = cx - ring;
      const x1 = cx + ring;
      const z0 = cz - ring;
      const z1 = cz + ring;
      for (let gz = z0; gz <= z1; gz++) {
        if (gz < 0 || gz >= rows) continue;
        // Interior rows only need their two edge columns; the rest was covered
        // by an earlier ring.
        const edgeRow = gz === z0 || gz === z1;
        const step = edgeRow ? 1 : Math.max(1, x1 - x0);
        for (let gx = x0; gx <= x1; gx += step) {
          if (gx < 0 || gx >= cols) continue;
          const c = gz * cols + gx;
          const to = start[c + 1];
          for (let k = start[c]; k < to; k++) {
            const i = items[k];
            const dx = px[i] - x;
            const dz = pz[i] - z;
            const d = dx * dx + dz * dz;
            if (d < bestD) { bestD = d; best = i; }
          }
        }
      }
      // Anything outside the searched box is at least ring*cell away, so once
      // the best beats that the answer is provably final.
      if (best >= 0 && bestD <= (ring * cell) * (ring * cell)) break;
    }

    if (best < 0) {
      // Degenerate fallback: decimated scan. Only reachable if the query is
      // astronomically far outside the grid.
      const s = this.stride * 4;
      for (let i = 0; i < this.count; i += s) {
        const dx = px[i] - x;
        const dz = pz[i] - z;
        const d = dx * dx + dz * dz;
        if (d < bestD) { bestD = d; best = i; }
      }
      if (best < 0) best = 0;
    }
    return best;
  }
}


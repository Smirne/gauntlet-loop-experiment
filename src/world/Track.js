// world/Track.js — the track data model and every spatial query the game asks of it.
//
// One idea underpins this file: **t is uniform in distance**. A raw
// CatmullRomCurve3 is parameterised by segment index, so a control point every
// 40 u and another every 120 u means a constant step in u covers wildly
// different ground. Every consumer downstream — AI lookahead in metres, lap
// progress, position ranking, the minimap, checkpoint spacing, the racing-line
// solver — silently breaks under that. So the spline is built once, its arc
// length is measured by dense chordal integration, and then the whole thing is
// resampled into a flat table of frames spaced evenly by *distance*. After that
// t*length is a distance, full stop.
//
// The second idea is that geometry and physics must agree bit for bit. The
// visual ribbon that TrackBuilder sweeps is generated by calling the same
// surfacePoint()/heightAt() this file hands the suspension. There is no
// "collision mesh" that drifts from the render mesh, because there is only one
// height function.
//
// Everything hot is a typed array. nearestT() is called for every car on every
// physics tick (8 cars x 120 Hz) and heightAt() four times more often than
// that, so both run against a CSR spatial hash built at load, never a scan.

import * as THREE from 'three';
import { clamp, lerp, smoothstep, fbm2D, makeRng } from '../core/Random.js';

